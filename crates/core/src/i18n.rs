#[cfg(test)]
mod tests {
    #[test]
    fn translates_and_falls_back() {
        super::set_english(true);
        assert_eq!(super::t("Fechar"), "Close");
        assert_eq!(super::t("sem tradução"), "sem tradução");
        let n = 3;
        assert_eq!(crate::tr!("{n} faixas", "{n} tracks"), "3 tracks");
        super::set_english(false);
        assert_eq!(super::t("Fechar"), "Fechar");
        assert_eq!(crate::tr!("{} faixas", "{} tracks", n), "3 faixas");
    }

    #[test]
    fn no_duplicate_keys() {
        let mut seen = std::collections::HashSet::new();
        for (pt, _) in super::EN {
            assert!(seen.insert(pt), "repetido: {pt}");
        }
    }
}
