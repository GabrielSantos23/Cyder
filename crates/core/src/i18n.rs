//! Idioma dos textos: o app é escrito em português e `t` troca pelo inglês quando ele está escolhido.
//! Textos com valores no meio usam `tr!`, com as duas versões lado a lado.
use std::collections::HashMap;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicBool, Ordering};

static ENGLISH: AtomicBool = AtomicBool::new(false);

pub fn set_english(on: bool) {
    ENGLISH.store(on, Ordering::Relaxed);
}

pub fn english() -> bool {
    ENGLISH.load(Ordering::Relaxed)
}

/// Idioma pedido ao Spotify (tela inicial, nomes de categorias e playlists dele).
pub fn spotify_language() -> &'static str {
    if english() { "en" } else { "pt-BR" }
}

/// O texto no idioma escolhido. Sem tradução, o próprio texto.
pub fn t(pt: &str) -> &str {
    if !english() {
        return pt;
    }
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| EN.iter().copied().collect()).get(pt).copied().unwrap_or(pt)
}

/// `format!` no idioma escolhido: `tr!("Abrir {nome}", "Open {nome}")`, com os mesmos valores nas duas.
#[macro_export]
macro_rules! tr {
    ($pt:literal, $en:literal $(, $arg:expr)* $(,)?) => {
        if $crate::i18n::english() { format!($en $(, $arg)*) } else { format!($pt $(, $arg)*) }
    };
}

